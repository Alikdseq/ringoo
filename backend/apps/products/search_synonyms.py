"""
Единая логика синонимов для поиска: рус ↔ англ (и любые пары).
Используется в списке товаров, автодополнении и фильтре по бренду.
Чтобы новый товар (например Table) находился по запросу «Доска» — добавьте пару ниже.
"""

# Пары (вариант_1, вариант_2): поиск по любому из них находит оба.
# Регистр при сравнении не учитывается; в запрос подставляются оба варианта.
# Для новых товаров: добавьте пару (как пользователь введёт, как в каталоге).
SEARCH_SYNONYM_PAIRS = [
    # Бренды / устройства
    ("айфон", "iphone"),
    ("айфоны", "iphone"),
    ("макбук", "macbook"),
    ("мак бук", "macbook"),
    ("мак-бук", "macbook"),
    ("дайсон", "dyson"),
    ("эппл", "apple"),
    ("самсунг", "samsung"),
    ("ксоми", "xiaomi"),
    # Товары: как пользователь может написать ↔ как в названии/каталоге
    ("доска", "table"),
    ("стол", "table"),
    ("планшет", "tablet"),
]


def get_search_terms(raw: str) -> list[str]:
    """
    Возвращает список терминов для поиска: исходная строка + все синонимы (в обе стороны).
    Учитываются и вся фраза, и вхождение ключей синонимов в ней (например «купить айфон» → + iphone).
    Используется везде: список товаров (search), автодополнение (q), фильтр по бренду (brand).
    """
    if not raw:
        return []
    base = raw.strip()
    if not base:
        return []
    seen = {base.lower()}
    terms = [base]
    lower = base.lower()

    for a, b in SEARCH_SYNONYM_PAIRS:
        a_l, b_l = a.lower(), b.lower()
        if a_l in lower:
            if b_l not in seen:
                seen.add(b_l)
                terms.append(b)
        if b_l in lower:
            if a_l not in seen:
                seen.add(a_l)
                terms.append(a)

    return terms
